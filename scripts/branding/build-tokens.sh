import json
import sys

token_path = Path(sys.argv[1])
output_css = Path(sys.argv[2])
output_light_css = Path(sys.argv[3])
output_prefix = sys.argv[4]

payload = json.loads(token_path.read_text(encoding="utf-8"))
colors = payload.get("color", {})
fonts = payload.get("fontFamily", {})

def read_token(section, key, default):
