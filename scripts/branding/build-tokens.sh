    f"  --pgn-typography-headings-font-family: {heading_font};",
    f"  --pgn-color-primary-base: {primary};",
    f"  --pgn-color-secondary-base: {secondary};",
    f"  --pgn-color-brand-base: {primary};",
    f"  --pgn-color-primary-100: {lighten(primary, 0.58)};",
    f"  --pgn-color-primary-200: {lighten(primary, 0.42)};",
    f"  --pgn-color-primary-300: {lighten(primary, 0.28)};",
    f"  --pgn-color-primary-400: {lighten(primary, 0.16)};",
    f"  --pgn-color-primary-500: {primary};",
    f"  --pgn-color-primary-700: {darken(primary)};",
    f"  --pgn-color-brand-700: {darken(primary)};",
    f"  --pgn-color-success-base: {success};",
    f"  --pgn-color-info-base: {info};",
    f"  --pgn-color-info-200: {lighten(info)};",
    f"  --pgn-color-info-300: {lighten(info, 0.32)};",
    f"  --pgn-color-info-500: {info};",
    f"  --pgn-color-info-700: {darken(info, 0.18)};",
    f"  --pgn-color-warning-base: {warning};",
