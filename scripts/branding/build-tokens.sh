    return "#" + "".join(f"{max(0, min(255, round(channel * (1 - factor)))):02X}" for channel in channels)

def lighten(hex_value, factor=0.42):
    value = hex_value.lstrip("#")
    channels = [int(value[i:i+2], 16) for i in range(0, 6, 2)]
    return "#" + "".join(f"{max(0, min(255, round(channel + (255 - channel) * factor))):02X}" for channel in channels)

primary = read_token(colors, "primary", "#AB3B78")
secondary = read_token(colors, "secondary", "#237072")
success = read_token(colors, "success", "#2C6E49")
info = read_token(colors, "info", primary)
warning = read_token(colors, "warning", secondary)
danger = read_token(colors, "danger", darken(primary, 0.35))
body_font = normalize_font(read_token(fonts, "sans-serif", ""))
heading_font = normalize_font(read_token(fonts, "heading", body_font))

lines = [
    f"/* Generated by build-tokens.sh for {output_prefix} tenant brand override delta. */",
    ":root {",
    f"  --mereka-font-body: {body_font};",
    f"  --mereka-font-heading: {heading_font};",
    f"  --mereka-color-magenta: {primary};",
    f"  --mereka-color-magenta-dark: {darken(primary)};",
    f"  --mereka-color-teal: {secondary};",
    f"  --mereka-color-blue: {info};",
    f"  --mereka-color-sky: {lighten(info)};",
    f"  --mereka-color-success: {success};",
    f"  --mereka-color-warning: {warning};",
    f"  --mereka-color-danger: {danger};",
    f"  --mereka-mfe-gradient: linear-gradient(120deg, {primary} 0%, {secondary} 58%, {info} 100%);",
    f"  --pgn-typography-font-family-sans-serif: {body_font};",
