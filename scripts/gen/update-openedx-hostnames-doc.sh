#!/usr/bin/env bash
# Generate docs/reference/operations/OPENEDX_HOSTNAMES.md from scripts/shared/config.sh.
#
# Why:
# - Hostnames are easy to let drift across docs/specs/scripts.
# - This keeps the hostname registry deterministic and low-effort for future agents.
#
# Usage:
#   ./scripts/gen/update-openedx-hostnames-doc.sh
#
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
source "$REPO_ROOT/scripts/shared/config.sh"

OUT="$REPO_ROOT/docs/reference/operations/OPENEDX_HOSTNAMES.md"

last_updated="$(
  git -C "$REPO_ROOT" log -1 --format=%cs 2>/dev/null || date -u +%Y-%m-%d
)"

prod_lms_hosts=("$LMS_DOMAIN" "$BIJI_DOMAIN" "$SKILLOURFUTURE_DOMAIN")
prod_alias_hosts=("$PREVIEW_DOMAIN")
prod_studio_hosts=("$STUDIO_DOMAIN" "$BIJI_STUDIO_DOMAIN")
prod_mfe_hosts=("$MFE_DOMAIN" "$BIJI_MFE_DOMAIN")
prod_services=("$DISCOVERY_DOMAIN" "$ECOMMERCE_DOMAIN" "$CREDENTIALS_DOMAIN" "$NOTES_DOMAIN" "$FORUM_DOMAIN")

dev_hosts=(
  "$DEV_LMS_DOMAIN"
  "$DEV_PREVIEW_DOMAIN"
  "$DEV_STUDIO_DOMAIN"
  "$DEV_MFE_DOMAIN"
  "$DEV_DISCOVERY_DOMAIN"
  "$DEV_ECOMMERCE_DOMAIN"
  "$DEV_CREDENTIALS_DOMAIN"
  "$DEV_NOTES_DOMAIN"
  "$DEV_FORUM_DOMAIN"
)

cat >"$OUT" <<EOF
# Open edX Hostnames Registry
_Audience: Platform Eng • Last updated: ${last_updated}_

> This file is generated by \`scripts/gen/update-openedx-hostnames-doc.sh\`.
> Edit \`scripts/shared/config.sh\` (domain defaults) and regenerate.

This is the canonical list of **public hostnames** for the Open edX ecosystem we operate here.

Why this exists:
- We run **multiple microsites** on one Open edX stack.
- Missing or wrong hostnames cause confusing “SSO is missing” symptoms (because redirects depend on Host).
- We want deterministic verification: no guessing, no tribal knowledge.

## Drift Check

Compare expected hostnames vs deployed Ingress hosts:
\`\`\`bash
./scripts/qa/list-openedx-hostnames.sh
\`\`\`

## Production (GKE)

LMS microsites (tenant roots):
EOF

for h in "${prod_lms_hosts[@]}"; do
  [[ -n "$h" ]] && echo "- \`$h\`" >>"$OUT"
done

cat >>"$OUT" <<EOF

LMS aliases (same LMS, extra hostnames):
EOF

for h in "${prod_alias_hosts[@]}"; do
  [[ -n "$h" ]] && echo "- \`$h\`" >>"$OUT"
done

cat >>"$OUT" <<EOF

Studio:
EOF

for h in "${prod_studio_hosts[@]}"; do
  [[ -n "$h" ]] && echo "- \`$h\`" >>"$OUT"
done

cat >>"$OUT" <<EOF

MFE apps:
EOF

for h in "${prod_mfe_hosts[@]}"; do
  [[ -n "$h" ]] && echo "- \`$h\`" >>"$OUT"
done

cat >>"$OUT" <<EOF

Shared ecosystem services (still part of the Open edX ecosystem):
EOF

for h in "${prod_services[@]}"; do
  [[ -n "$h" ]] && echo "- \`$h\`" >>"$OUT"
done

cat >>"$OUT" <<EOF

SSO / IdP:
- Authentik: \`auth0.mereka.io\`

## Development (VPS kind)

Public dev hostnames:
EOF

for h in "${dev_hosts[@]}"; do
  [[ -n "$h" ]] && echo "- \`$h\`" >>"$OUT"
done

cat >>"$OUT" <<'EOF'

## Development (kind-local)

When working against the kind cluster locally, these wildcard hostnames can exist too:
- `lms.lvh.me`
- `preview.lms.lvh.me`
- `studio.lms.lvh.me`
- `apps.lms.lvh.me`

These are convenience hostnames for local testing and are not part of the public `.mereka.dev` surface.
EOF

echo "Wrote $OUT"
